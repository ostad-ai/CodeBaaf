# 04 - Conditionals (If, Elif, Else)
# Making decisions in your code.

temperature = 22

if temperature > 30:
    print("It's hot outside! Turn on the AC.")
elif temperature > 20:
    print("It's a nice, warm day.")
elif temperature > 10:
    print("It's a bit chilly. Wear a jacket.")
else:
    print("It's freezing! Stay inside.")